val roomVersion = "2.7.1"

// Defensive: nothing (a transitive dependency, or a toolchain that substitutes
// its own processor version) may move one Room artifact off roomVersion. A
// compiler newer than the runtime is exactly what crashes KSP.
configurations.configureEach {
    resolutionStrategy {
        force(
            "androidx.room:room-runtime:$roomVersion",
            "androidx.room:room-ktx:$roomVersion",
            "androidx.room:room-common:$roomVersion",
            "androidx.room:room-compiler:$roomVersion",
        )
    }
}

